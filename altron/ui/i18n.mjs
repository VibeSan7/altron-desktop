function valueAt(tree, key) {
  return key.split('.').reduce((value, part) => value?.[part], tree);
}

export function translate(language, key, ...args) {
  const locale = language === 'ru' ? 'ru' : 'en';
  const value = valueAt(messages[locale], key) ?? valueAt(messages.en, key);
  if (typeof value === 'function') return value(...args);
  return typeof value === 'string' ? value : key;
}

export const russianT = (key, ...args) => translate('ru', key, ...args);

export const defaultLocalizer = {
  useI18n: () => ({t: russianT}),
};

export function readLanguage(storage) {
  const value = storage.get('language', 'hermes');
  return supportedLanguages.has(value) ? value : 'hermes';
}

export function writeLanguage(storage, language) {
  const value = supportedLanguages.has(language) ? language : 'hermes';
  storage.set('language', value);
  return value;
}

export function createI18n(React, sdk, ctx, pluginId) {
  const {createElement: h, createContext, useCallback, useContext, useMemo, useState} = React;
  const LanguageContext = createContext(null);
  ctx.i18n.register(messages);

  function Provider({children}) {
    const hermesT = sdk.usePluginI18n(pluginId);
    const [language, setLanguageState] = useState(() => readLanguage(ctx.storage));
    const setLanguage = useCallback(value => setLanguageState(writeLanguage(ctx.storage, value)), []);
    const t = useMemo(() => language === 'hermes'
      ? hermesT
      : (key, ...args) => translate(language, key, ...args), [hermesT, language]);
    const value = useMemo(() => ({language, setLanguage, t}), [language, setLanguage, t]);
    return h(LanguageContext.Provider, {value}, children);
  }

  function useI18n() {
    const value = useContext(LanguageContext);
    if (!value) throw new Error('Altron locale provider is missing');
    return value;
  }

  function LanguageSelector() {
    const {language, setLanguage, t} = useI18n();
    const label = t('language.label');
    return h('label', {style: {display: 'inline-flex', gap: 8, alignItems: 'center'}},
      h('span', null, label),
      h('select', {
        'aria-label': label,
        value: language,
        onChange: event => setLanguage(event.target.value),
        style: {color: 'inherit', background: 'var(--ui-background)', padding: 6},
      },
      h('option', {value: 'hermes'}, t('language.hermes')),
      h('option', {value: 'ru'}, t('language.ru')),
      h('option', {value: 'en'}, t('language.en'))));
  }

  return {Provider, LanguageSelector, useI18n};
}
